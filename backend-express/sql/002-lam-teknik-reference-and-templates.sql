CREATE INDEX IF NOT EXISTS idx_institutions_name ON institutions(name);
CREATE INDEX IF NOT EXISTS idx_institutions_lam_teknik_id ON institutions(lam_teknik_id);
CREATE INDEX IF NOT EXISTS idx_institutions_active ON institutions(is_active);

COMMENT ON TABLE institutions IS 'Reference: Perguruan Tinggi registered at LAM Teknik (scraped from SAKTI register page)';
COMMENT ON COLUMN institutions.lam_teknik_id IS 'ID at LAM Teknik SAKTI system (for sync reference)';
