-- 3. Document Template Validation (AI Embedding)
-- ============================================================

CREATE TABLE IF NOT EXISTS document_templates (
    id SERIAL PRIMARY KEY,
    template_code VARCHAR(100) UNIQUE NOT NULL,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    file_path TEXT NOT NULL,
    file_hash VARCHAR(64),
    extracted_text TEXT,
    embedding vector(768),
    min_similarity_threshold DECIMAL(4,3) DEFAULT 0.750,
    max_file_size_kb INTEGER DEFAULT 1024,
    allowed_mime_types TEXT[] DEFAULT ARRAY['application/pdf'],
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_document_templates_code ON document_templates(template_code);
CREATE INDEX IF NOT EXISTS idx_document_templates_active ON document_templates(is_active);

COMMENT ON TABLE document_templates IS 'Templates for validating uploaded PDFs via embedding similarity';
COMMENT ON COLUMN document_templates.embedding IS 'E5 embedding (768 dim) of extracted_text';

CREATE TABLE IF NOT EXISTS document_validations (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id UUID REFERENCES users(id) ON DELETE SET NULL,
    template_id INTEGER REFERENCES document_templates(id) ON DELETE SET NULL,
    template_code VARCHAR(100) NOT NULL,
    file_name VARCHAR(500) NOT NULL,
    file_hash VARCHAR(64),
    file_size_bytes INTEGER,
    mime_type VARCHAR(100),
    extracted_text TEXT,
    extracted_text_length INTEGER,
    embedding vector(768),
    similarity_score DECIMAL(6,4),
    threshold DECIMAL(4,3),
    is_valid BOOLEAN,
    validation_errors JSONB,
    context VARCHAR(100),
    metadata JSONB,
    error_message TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_document_validations_user ON document_validations(user_id);
CREATE INDEX IF NOT EXISTS idx_document_validations_template ON document_validations(template_id);
CREATE INDEX IF NOT EXISTS idx_document_validations_valid ON document_validations(is_valid);
CREATE INDEX IF NOT EXISTS idx_document_validations_created ON document_validations(created_at);

COMMENT ON TABLE document_validations IS 'Log of document validation attempts vs templates';

