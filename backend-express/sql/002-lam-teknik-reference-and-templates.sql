-- Backfill: map existing free-text to FK where exact match exists
UPDATE users u
SET institution_id = i.id
FROM institutions i
WHERE u.institution IS NOT NULL
  AND u.institution_id IS NULL
  AND LOWER(TRIM(u.institution)) = LOWER(TRIM(i.name));

UPDATE users u
SET program_studi_id = ps.id
FROM program_studi ps
WHERE u.program_studi IS NOT NULL
  AND u.program_studi_id IS NULL
  AND LOWER(TRIM(u.program_studi)) = LOWER(TRIM(ps.name));

